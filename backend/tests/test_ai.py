def test_conversation_memory_is_isolated_by_session():
  memory = ConversationMemoryManager()
  memory.add_exchange("session-a", "Question A", "Answer A", "en")
  memory.add_exchange("session-b", "Question B", "Answer B", "en")

  assert memory.get("session-a").messages[0]["content"] == "Question A"
  assert memory.get("session-b").messages[0]["content"] == "Question B"
