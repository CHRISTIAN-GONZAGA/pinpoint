def test_retrieval_finds_route_information():
  store = InMemoryVectorStore()
  store.add_documents(
    [
      {
        "document_id": "route-2",
        "title": "R2 — Junction to Robinsons",
        "category": "transport",
        "chunks": [
          "Route R2 connects Baan Junction to Robinsons Place Butuan.",
        ],
        "metadata": {"route_code": "R2"},
      }
    ]
  )
  results = store.search("Which jeep goes to Robinsons?")
  assert results
  assert "R2" in results[0].content or "Robinsons" in results[0].content


def test_chat_endpoint(client, monkeypatch):
  class FakeChat:
    def chat(self, **kwargs):
      return {
        "response": "Generated by Gemini",
        "language": kwargs["response_language"] or "en",
        "session_id": kwargs["session_id"] or "test-session",
        "sources": [],
        "actions": [],
        "retrieval_confidence": 0.0,
      }

  monkeypatch.setattr("app.ai.routes._get_chat", lambda: FakeChat())
  response = client.post(
    "/api/ai/chat",
    json={"message": "Which jeep goes to Robinsons Place Butuan?"},
  )
  assert response.status_code == 200
  data = response.get_json()
  assert data["response"] == "Generated by Gemini"
  assert data["language"] in {"en", "tl", "ceb", "mixed"}
  assert data["session_id"] == "test-session"


